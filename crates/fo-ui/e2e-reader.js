// Reader walk-through in the browser preview (mock backend).
const { chromium } = require(process.env.PLAYWRIGHT || 'playwright');
const OUT = process.env.OUT || '/tmp/reader-shots';
const fail = (m) => { console.log('FAIL ' + m); process.exitCode = 1; };
(async () => {
  require('fs').mkdirSync(OUT, { recursive: true });
  const b = await chromium.launch({ executablePath: process.env.CHROME || undefined, args: ['--no-sandbox'] });
  for (const [name, vp, q] of [['desktop', { width: 1280, height: 860 }, ''], ['android', { width: 400, height: 860 }, '&platform=android']]) {
    const p = await b.newPage({ viewport: vp });
    const errors = [];
    p.on('pageerror', (e) => errors.push(e.message));
    await p.goto((process.env.URL || 'http://localhost:1420/index.html') + '?tab=read' + q);
    await p.waitForTimeout(700);
    await p.getByRole('button', { name: 'choose files' }).click();
    await p.waitForTimeout(1200);
    if (!(await p.locator('.pdf-reader').count())) fail(name + ': PDF did not open');
    const spans = await p.locator('.text-layer span').count();
    if (spans < 5) fail(name + ': text layer has ' + spans + ' spans');
    await p.screenshot({ path: `${OUT}/${name}-pdf.png` });
    await p.locator('.find input').fill('river');
    await p.locator('.find input').press('Enter');
    await p.waitForTimeout(700);
    const count = await p.locator('.find-count').innerText();
    if (!/of \d+/.test(count)) fail(name + ': search count is ' + JSON.stringify(count));
    if (!(await p.locator('.hits i.now').count())) fail(name + ': no current highlight');
    await p.screenshot({ path: `${OUT}/${name}-pdf-search.png` });
    await p.getByRole('button', { name: 'Close and go back to your files' }).click();
    await p.waitForTimeout(400);
    await p.locator('.file-row', { hasText: 'The long walk.epub' }).getByRole('button', { name: 'Read' }).click();
    await p.waitForTimeout(800);
    const prose = await p.locator('.prose').innerText();
    if (!prose.includes('The valley road')) fail(name + ': chapter 1 missing');
    await p.screenshot({ path: `${OUT}/${name}-book.png` });
    await p.locator('.prose a', { hasText: 'river ferries' }).click();
    await p.waitForTimeout(300);
    if (!(await p.locator('.link-note').innerText()).includes('example.org/ferries')) fail(name + ': link note');
    await p.locator('.prose a', { hasText: 'the crossing' }).click();
    await p.waitForTimeout(700);
    if (!(await p.locator('.prose').innerText()).includes('The ford')) fail(name + ': chapter link');
    await p.screenshot({ path: `${OUT}/${name}-book-ch2.png` });
    await p.getByRole('button', { name: 'Close and go back to your files' }).click();
    await p.waitForTimeout(300);
    await p.locator('.file-row', { hasText: 'meeting notes.md' }).getByRole('button', { name: 'Read' }).click();
    await p.waitForTimeout(600);
    await p.screenshot({ path: `${OUT}/${name}-md.png` });
    await p.getByRole('button', { name: 'Close and go back to your files' }).click();
    await p.waitForTimeout(300);
    await p.locator('.file-row', { hasText: 'river at dusk.jpg' }).getByRole('button', { name: 'Read' }).click();
    await p.waitForTimeout(600);
    if (!(await p.locator('.details').innerText()).includes('Fujifilm')) fail(name + ': EXIF');
    await p.screenshot({ path: `${OUT}/${name}-image.png` });
    await p.getByRole('button', { name: 'Close and go back to your files' }).click();
    await p.waitForTimeout(300);
    if (!(await p.locator('.file-row', { hasText: '.docx' }).innerText()).includes("Can't be read yet")) fail(name + ': docx row');
    await p.screenshot({ path: `${OUT}/${name}-list.png` });
    if (errors.length) fail(name + ': page errors ' + errors.join(' | '));
    await p.close();
  }
  await b.close();
  console.log(process.exitCode ? 'DONE with failures' : 'PASS');
})();
